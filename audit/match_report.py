#!/usr/bin/env python3
"""Build audit/MATCHING.md: engine-gearbox-propeller matching for every preset,
with the chosen candidate, the full power ledger and the rejection tally."""
import json, os, subprocess, sys, collections

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
html = os.path.join(ROOT, "app", "yanmar_engine_propeller_selector.html")

dom = json.loads(subprocess.run(["node", os.path.join(HERE, "js", "dump_dom.cjs"), html],
                                capture_output=True, text=True, check=True).stdout)

def cat(reason):
    r = reason.lower()
    if "grossly oversized" in r: return "grossly oversized (<12 % load)"
    if "no gear ratio gives a feasible" in r: return "no feasible/cavitation-free propeller in the diameter limit"
    if "duty-cycle" in r or "annual operation" in r or "rated-power band" in r: return "duty-cycle (YANMAR rating) limit"
    if "below the minimum brake power" in r: return "under-powered"
    if "outside their physical range" in r: return "propulsion coefficients out of range"
    if "diameter" in r: return "propeller diameter limit"
    return "other"

lines = ["# Engine–gearbox–propeller matching — audited build",
         "",
         "Generated by `audit/match_report.py` from the shipped application "
         "(`app/yanmar_engine_propeller_selector.html`) run headless in jsdom. "
         "Every number below is produced by the application itself; the audit's "
         "independently recomputed checks are in `TEST_REPORT.md`. A candidate is "
         "reported only when it clears every gate; where the application falls back "
         "to a ``closest`` candidate that is stated and its violations are listed.",
         ""]
for p in dom["presets"]:
    lines.append("## %s" % p["id"])
    if not p.get("ok") or not p.get("primary"):
        lines.append("")
        lines.append("**No compliant match.** %s" % "; ".join(p.get("errors") or []))
        lines.append("")
        continue
    c, r = p["primary"], p["res"]
    lines.append("")
    lines.append("| quantity | value |")
    lines.append("|---|---|")
    rows = [
        ("Resistance method", r["method"]),
        ("Total resistance R_T", "%.2f kN" % (r["Rtotal"] / 1000)),
        ("Effective power P_E", "%.1f kW" % (r["PE"] / 1000)),
        ("Method domain status", r["domainStatus"]),
        ("Engine / rating", "%s %s (%s) — %s kW @ %s rpm"
         % (c["model"], c["ymark"], c["duty"], c["kW"], c["rpm"])),
        ("Marine gear / ratio", "%s, i = %.2f" % (c["gear"], c["ratio"])),
        ("Propeller shaft speed", "%.0f rpm" % c["nShaft"]),
        ("Brake power required P_B", "%.1f kW per engine" % c["PB"]),
        ("Delivered power P_D", "%.1f kW" % c["PD"]),
        ("Service load", "%.1f %% of rating" % (c["load"] * 100)),
        ("Wake fraction w / thrust deduction t / eta_R",
         "%.3f / %.3f / %.3f" % (c["w"], c["t"], c["etaR"])),
        ("Shaft / gear efficiency used", "%.3f / %.3f" % (p["inp"]["etaShaft"], p["inp"]["etaGear"])),
        ("Overall propulsive efficiency eta_D", "%.4f" % c["etaD"]),
        ("Propeller D / P/D / J / Z / A_E/A_0",
         "%.3f m / %.3f / %.3f / %d / %.2f" % (c["D"], c["PDprop"], c["J"], c["Z"], c["EAR"])),
        ("Open-water efficiency eta_O", "%.4f" % c["etaO"]),
        ("K_T / K_Q", "%.4f / %.5f" % (c["KT"], c["KQ"])),
        ("Burrill tau_act / tau_c, Keller A_E/A_0 required",
         "%.4f / %.4f, %.3f" % (c["tauAct"], c["tauC"], c["EARreq"])),
        ("Tip speed", "%.1f m/s (limit check %s)" % (c["Vtip"], "pass" if c["tipOK"] else "FAIL")),
        ("Installed mass (engine + gear)", ("%.0f kg" % c["installedMass"]) if c["installedMass"] else "not stated (see basis)"),
        ("Status", c["status"]),
    ]
    for k, v in rows:
        lines.append("| %s | %s |" % (k, v))
    if c.get("violations"):
        lines.append("")
        lines.append("**Constraint violations carried into the report:**")
        for v in c["violations"]:
            lines.append("- %s" % v)
    tally = collections.Counter(cat(x["reason"]) for x in p["rejected"])
    lines.append("")
    lines.append("**Rejected ratings: %d.** Rejection tally:" % p["rejectedCount"])
    lines.append("")
    lines.append("| rejection reason | count |")
    lines.append("|---|---|")
    for k, v in tally.most_common():
        lines.append("| %s | %d |" % (k, v))
    lines.append("")
    lines.append("First rejections in the candidate order (model / rating / reason):")
    lines.append("")
    for x in p["rejected"][:8]:
        lines.append("- %s %s %s — %s" % (x["model"], x["ymark"], x["kW"], x["reason"]))
    lines.append("")
    lines.append("Alternates offered: %s" % (", ".join(p["alternates"]) or "none"))
    lines.append("")

with open(os.path.join(HERE, "MATCHING.md"), "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
print("written audit/MATCHING.md (%d presets)" % len(dom["presets"]))
